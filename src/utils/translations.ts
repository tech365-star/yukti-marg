/**
 * Checks if a string already contains Devanagari (Hindi) script characters
 */
export function hasDevanagari(text: string): boolean {
  return /[\u0900-\u097F]/.test(text);
}

/**
 * Translates a single text string from English to Hindi.
 * If text is already in Hindi or empty, returns as is.
 */
export function translateText(rawText: string): string {
  if (!rawText || typeof rawText !== 'string') return rawText;

  // Don't translate if it already contains Hindi characters
  if (hasDevanagari(rawText)) return rawText;

  // Don't translate pure numbers, currency numbers, dates or code/symbols
  const trimmed = rawText.trim();
  if (!trimmed || /^[\d\s\.,;:!@#\$%\^&\*\(\)_+\-=\[\]\{\}\|\\<>\/?₹\n\r\t]+$/.test(trimmed)) {
    return rawText;
  }

  // Check exact dictionary match
  if (DICTIONARY[trimmed]) {
    // preserve leading and trailing whitespace
    const leading = rawText.match(/^\s*/)?.[0] || '';
    const trailing = rawText.match(/\s*$/)?.[0] || '';
    return leading + DICTIONARY[trimmed] + trailing;
  }

  // Check lowercase match in dictionary
  const trimmedLower = trimmed.toLowerCase();
  for (const [enKey, hiVal] of Object.entries(DICTIONARY)) {
    if (enKey.toLowerCase() === trimmedLower) {
      const leading = rawText.match(/^\s*/)?.[0] || '';
      const trailing = rawText.match(/\s*$/)?.[0] || '';
      return leading + hiVal + trailing;
    }
  }

  // If text contains multiple punctuation-separated segments, translate each
  if (trimmed.includes('•') || trimmed.includes('|') || trimmed.includes(' - ') || trimmed.includes(':')) {
    const delimiter = trimmed.includes('•') ? '•' : trimmed.includes('|') ? '|' : trimmed.includes(' - ') ? ' - ' : ':';
    const parts = trimmed.split(delimiter);
    if (parts.length > 1) {
      const translatedParts = parts.map((part) => translateText(part));
      const leading = rawText.match(/^\s*/)?.[0] || '';
      const trailing = rawText.match(/\s*$/)?.[0] || '';
      return leading + translatedParts.join(` ${delimiter.trim()} `) + trailing;
    }
  }

  // Check if string starts with "Total ", "Domain ", etc.
  const prefixPatterns: Array<[RegExp, string]> = [
    [/^Total\s+(.+)$/i, 'कुल '],
    [/^Across\s+(.+)$/i, 'पूरे '],
    [/^Submitted by\s+(.+)$/i, 'प्रस्तुतकर्ता: '],
    [/^Assigned to\s+(.+)$/i, 'आवंटित: '],
    [/^Status:\s+(.+)$/i, 'स्थिति: '],
    [/^Category:\s+(.+)$/i, 'श्रेणी: '],
    [/^District:\s+(.+)$/i, 'ज़िला: '],
    [/^Domain\s+(\d+)$/i, 'डोमेन $1'],
    [/^Domain\s+(.+)$/i, 'डोमेन '],
    [/^(\d+)\s+Challenges\s*→$/i, '$1 समस्याएं →'],
    [/^(\d+)\s+Challenges$/i, '$1 समस्याएं']
  ];

  for (const [regex, hiPrefix] of prefixPatterns) {
    const match = trimmed.match(regex);
    if (match && match[1]) {
      const translatedRest = translateText(match[1]);
      const leading = rawText.match(/^\s*/)?.[0] || '';
      const trailing = rawText.match(/\s*$/)?.[0] || '';
      return leading + hiPrefix + translatedRest + trailing;
    }
  }

  // Handle "X days ago", "X hours ago", etc.
  const timeMatch = trimmed.match(/^(\d+)\s+(days?|hours?|mins?|minutes?|months?)\s+ago$/i);
  if (timeMatch) {
    const num = timeMatch[1];
    const unit = timeMatch[2].toLowerCase();
    let unitHi = 'दिन';
    if (unit.startsWith('hour')) unitHi = 'घंटे';
    if (unit.startsWith('min')) unitHi = 'मिनट';
    if (unit.startsWith('month')) unitHi = 'महीने';
    return `${num} ${unitHi} पहले`;
  }

  // If text is a phrase made of words in WORD_MAP, replace matching words
  // (Only for text with length < 100 characters to keep layout clean and readable)
  if (trimmed.length < 100) {
    let replaced = trimmed;
    let anyReplaced = false;

    // Check sorted keys by length descending to match compound words first
    const sortedKeys = Object.keys(WORD_MAP).sort((a, b) => b.length - a.length);
    for (const word of sortedKeys) {
      const regex = new RegExp(`\\b${word}\\b`, 'gi');
      if (regex.test(replaced)) {
        replaced = replaced.replace(regex, WORD_MAP[word]);
        anyReplaced = true;
      }
    }

    if (anyReplaced) {
      const leading = rawText.match(/^\s*/)?.[0] || '';
      const trailing = rawText.match(/\s*$/)?.[0] || '';
      return leading + replaced + trailing;
    }
  }

  return rawText;
}

// Build Reverse Dictionary (Hindi -> English)
export const REVERSE_DICTIONARY: Record<string, string> = {};
for (const [enKey, hiVal] of Object.entries(DICTIONARY)) {
  const trimmedHi = hiVal.trim();
  if (trimmedHi && !REVERSE_DICTIONARY[trimmedHi]) {
    REVERSE_DICTIONARY[trimmedHi] = enKey.trim();
  }
}

// Build Reverse Word Map (Hindi word -> English word)
export const REVERSE_WORD_MAP: Record<string, string> = {};
for (const [enWord, hiWord] of Object.entries(WORD_MAP)) {
  const trimmedHi = hiWord.trim();
  if (trimmedHi && !REVERSE_WORD_MAP[trimmedHi]) {
    REVERSE_WORD_MAP[trimmedHi] = enWord.trim();
  }
}

