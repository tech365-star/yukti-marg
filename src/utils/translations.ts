/**
 * Translates a single text string from Hindi to English.
 * If text does not contain Devanagari, returns as is.
 */
export function translateHindiToEnglish(rawText: string): string {
  if (!rawText || typeof rawText !== 'string') return rawText;
  if (!hasDevanagari(rawText)) return rawText;

  const trimmed = rawText.trim();
  if (!trimmed) return rawText;

  const leading = rawText.match(/^\s*/)?.[0] || '';
  const trailing = rawText.match(/\s*$/)?.[0] || '';

  // Check exact reverse dictionary
  if (REVERSE_DICTIONARY[trimmed]) {
    return leading + REVERSE_DICTIONARY[trimmed] + trailing;
  }

  // If text contains multiple punctuation-separated segments (•, |, -, :)
  if (trimmed.includes('•') || trimmed.includes('|') || trimmed.includes(' - ') || trimmed.includes(':')) {
    const delimiter = trimmed.includes('•') ? '•' : trimmed.includes('|') ? '|' : trimmed.includes(' - ') ? ' - ' : ':';
    const parts = trimmed.split(delimiter);
    if (parts.length > 1) {
      const translatedParts = parts.map((p) => translateHindiToEnglish(p));
      return leading + translatedParts.join(` ${delimiter.trim()} `) + trailing;
    }
  }

  // Handle prefix patterns
  const hiPrefixes: Array<[RegExp, string]> = [
    [/^कुल\s+(.+)$/, 'Total '],
    [/^पूरे\s+(.+)$/, 'Across '],
    [/^प्रस्तुतकर्ता:\s+(.+)$/, 'Submitted by: '],
    [/^आवंटित:\s+(.+)$/, 'Assigned to: '],
    [/^स्थिति:\s+(.+)$/, 'Status: '],
    [/^श्रेणी:\s+(.+)$/, 'Category: '],
    [/^ज़िला:\s+(.+)$/, 'District: '],
    [/^डोमेन\s+(\d+)$/, 'Domain $1'],
    [/^डोमेन\s+(.+)$/, 'Domain '],
    [/^(\d+)\s+समस्याएं\s*→$/, '$1 Challenges →'],
    [/^(\d+)\s+समस्याएं$/, '$1 Challenges']
  ];

  for (const [regex, enPrefix] of hiPrefixes) {
    const match = trimmed.match(regex);
    if (match && match[1]) {
      const translatedRest = translateHindiToEnglish(match[1]);
      return leading + enPrefix + translatedRest + trailing;
    }
  }

  // Handle "X दिन पहले", "X घंटे पहले", etc.
  const timeMatch = trimmed.match(/^(\d+)\s+(दिन|घंटे|घंटा|मिनट|महीने|महीना)\s+पहले$/);
  if (timeMatch) {
    const num = timeMatch[1];
    const unit = timeMatch[2];
    let unitEn = 'days ago';
    if (unit.startsWith('घंट')) unitEn = Number(num) === 1 ? 'hour ago' : 'hours ago';
    if (unit.startsWith('मिनट')) unitEn = Number(num) === 1 ? 'min ago' : 'mins ago';
    if (unit.startsWith('महीन')) unitEn = Number(num) === 1 ? 'month ago' : 'months ago';
    if (unit.startsWith('दिन')) unitEn = Number(num) === 1 ? 'day ago' : 'days ago';
    return leading + `${num} ${unitEn}` + trailing;
  }

  // Replace matched words in reverse word map
  let replaced = trimmed;
  let anyReplaced = false;
  const sortedHiWords = Object.keys(REVERSE_WORD_MAP).sort((a, b) => b.length - a.length);
  for (const hiWord of sortedHiWords) {
    if (replaced.includes(hiWord)) {
      replaced = replaced.split(hiWord).join(REVERSE_WORD_MAP[hiWord]);
      anyReplaced = true;
    }
  }

  if (anyReplaced) {
    return leading + replaced + trailing;
  }

  return rawText;
}

/**
 * Universal translator function (can be used directly in components: t(text, lang))
 */
export function t(text: string, lang: 'en' | 'hi' = 'en'): string {
  if (lang === 'en') return translateHindiToEnglish(text);
  return translateText(text);
}
